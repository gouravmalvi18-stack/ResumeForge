//package
import { PDFParse } from "pdf-parse";

//service
import GenerateAibasedReport from "../services/AiService.js";

//model
import AiReportModel from "../model/AiReport.model.js";

/**
 * @name CreateReportController
 * @description Generate an AI-based report based on the user's resume or self-description ,
 *              along with job description.User can provide either resume or self-description or both.
 * @access private
 */
export const CreateReportController = async (req, res) => {
  try {
    const user = req.user;
    const { jobDescription, selfDescription } = req.body;
    const file = req.file;
    let resumeContent;

    if (file) {
      const buffer = file.buffer;
      const parser = await new PDFParse({ data: buffer });
      resumeContent = await parser.getText();
    }

    if (!resumeContent && !selfDescription) {
      return res.status(400).json({
        message:
          "Either resume or self-description is required to generate the report.",
      });
    }

    if (!jobDescription) {
      return res.status(400).json({
        message: "Job description is required to generate the report.",
      });
    }

    const AiGenerateReport = await GenerateAibasedReport({
      jobDescription,
      selfDescription,
      resume: resumeContent?.text,
    });

    if (AiGenerateReport) {
      const NewReport = await AiReportModel.create({
        jobDescription,
        selfDescription,
        resume: resumeContent?.text,
        userId: user?.id,
        ...AiGenerateReport,
      });

      res.status(201).json({
        message: "AI-based report generated successfully.",
        report: NewReport,
      });
    }
  } catch (error) {
    res.status(500).json({
      message: `CreateReportController ERR :: ${error}`,
    });
  }
};

/**
 * @name GetAllReportController
 * @description  It will fetch all  reports which are generated by the user
 * @access private
 */
export const GetAllReportController = async (req, res) => {
  try {
    const user = req.user;

    const AllReport = await AiReportModel.find({ userId: user?.id });

    if (AllReport.length <= 0) {
      return res.status(404).json({
        message: "No reports found for the user.",
      });
    }

    res.status(200).json({
      message: "All reports fetched successfully.",
      AllReport,
    });
  } catch (error) {
    res.status(500).json({
      message: `GetAllReportController ERR :: ${error}`,
    });
  }
};

/**
 * @name GetReportByIdController
 * @description  It will fetch single report by id which is generated by the user
 * @access private
 */
export const GetReportByIdController = async (req, res) => {
  try {
    const { id } = req.params;
    const GetAReport = await AiReportModel.findById(id);

    if (!GetAReport) {
      return res.status(404).json({
        message: "No report not found",
      });
    }

    res.status(200).json({
      message: "Report fetched successfully.",
      Report: GetAReport,
    });
  } catch (error) {
    res.status(500).json({
      message: `GetReportByIdController ERR :: ${error}`,
    });
  }
};
